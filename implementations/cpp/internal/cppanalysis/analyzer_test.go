func TestAnalyzeFileReportsUnformattedSource(t *testing.T) {
	cfg := config.Default()
	cfg.Format.Enabled = true
	runner := &stubRunner{
		lookPath:    "/usr/bin/clang-format",
		runExitCode: 1,
		runOutput:   []byte("sample.c:1:1: error: code should be clang-formatted [-Wclang-format-violations]\n"),
	}

	diagnostics, err := NewWithRunner(cfg, runner).AnalyzeFile(AnalyzeFileRequest{
		Path:   "sample.c",
		Source: []byte("int main(void){return 0;}\n"),
	})
	if err != nil {
		t.Fatalf("AnalyzeFile returned error: %v", err)
	}

	if len(diagnostics) != 1 {
		t.Fatalf("expected 1 diagnostic, got %d: %#v", len(diagnostics), diagnostics)
	}
	if diagnostics[0].RuleID != RuleSourceFormat {
		t.Fatalf("expected rule %q, got %q", RuleSourceFormat, diagnostics[0].RuleID)
	}
	if diagnostics[0].Message != "file is not clang-format-formatted" {
		t.Fatalf("unexpected message %q", diagnostics[0].Message)
	}
	if diagnostics[0].Line != 1 || diagnostics[0].Column != 1 {
		t.Fatalf("expected location 1:1, got %d:%d", diagnostics[0].Line, diagnostics[0].Column)
	}

	if len(runner.lookCalls) != 1 || runner.lookCalls[0] != "clang-format" {
		t.Fatalf("expected LookPath(clang-format), got %#v", runner.lookCalls)
	}
	if len(runner.runCalls) != 1 {
		t.Fatalf("expected one Run call, got %#v", runner.runCalls)
	}
	call := runner.runCalls[0]
	if len(call) != 4 || call[0] != "/usr/bin/clang-format" || call[1] != "--dry-run" || call[2] != "--Werror" || call[3] != "sample.c" {
		t.Fatalf("unexpected Run args: %#v", call)
	}
}

