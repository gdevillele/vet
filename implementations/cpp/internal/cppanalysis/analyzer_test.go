func TestAnalyzeFileErrorsWhenClangFormatMissing(t *testing.T) {
	cfg := config.Default()
	cfg.Format.Enabled = true
	runner := &stubRunner{
		lookPathErr: errors.New("executable file not found in $PATH"),
	}

	diagnostics, err := NewWithRunner(cfg, runner).AnalyzeFile(AnalyzeFileRequest{
		Path:   "sample.c",
		Source: []byte("int main(void) { return 0; }\n"),
	})
	if err == nil {
		t.Fatalf("expected error when clang-format is missing")
	}
	if diagnostics != nil {
		t.Fatalf("expected nil diagnostics on tool error, got %#v", diagnostics)
	}
	if !strings.Contains(err.Error(), "clang-format not found in PATH") {
		t.Fatalf("expected missing-tool message, got %q", err.Error())
	}
	if !strings.Contains(err.Error(), "VET008") {
		t.Fatalf("expected VET008 mention in error, got %q", err.Error())
	}
}

