type stubRunner struct {
	lookPath    string
	lookPathErr error
	// runs maps "name arg1 arg2 ..." to scripted results. When empty, Run
	// falls back to runOutput/runExitCode/runErr.
	runs        map[string]stubRun
	runOutput   []byte
	runExitCode int
	runErr      error
	lookCalls   []string
	runCalls    [][]string
}

type stubRun struct {
	output   []byte
	exitCode int
	err      error
}

func (s *stubRunner) LookPath(file string) (string, error) {
	s.lookCalls = append(s.lookCalls, file)
	if s.lookPathErr != nil {
		return "", s.lookPathErr
	}
	if s.lookPath != "" {
		return s.lookPath, nil
	}
	return file, nil
}

func (s *stubRunner) Run(name string, args []string) ([]byte, int, error) {
	s.runCalls = append(s.runCalls, append([]string{name}, args...))
	key := name + " " + strings.Join(args, " ")
	if s.runs != nil {
		if result, ok := s.runs[key]; ok {
			return result.output, result.exitCode, result.err
		}
	}
	return s.runOutput, s.runExitCode, s.runErr
}

